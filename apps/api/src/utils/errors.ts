export class AppError extends Error {
  public readonly code: string;
  public readonly status: number;
  public readonly extra?: Record<string, unknown>;

  constructor(
    code: string,
    status: number,
    message: string,
    extra?: Record<string, unknown>,
  ) {
    super(message);
    this.name = "AppError";
    this.code = code;
    this.status = status;
    this.extra = extra;
  }
}
